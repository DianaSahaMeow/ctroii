ALTER TABLE defects ADD COLUMN IF NOT EXISTS closed_at TIMESTAMP;

-- Заполняем closed_at для уже принятых дефектов
UPDATE defects SET closed_at = updated_at WHERE status = 'ACCEPTED' AND closed_at IS NULL;

-- Таблица хронологии работ и оперативных заметок (например, "Отправил бригаду сантехников", "Заказали материал" и т.д.)
CREATE TABLE IF NOT EXISTS defect_comments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    defect_id BIGINT NOT NULL REFERENCES defects(id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES users(id),
    message TEXT NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_defect_comments_defect_id ON defect_comments(defect_id);
CREATE INDEX IF NOT EXISTS idx_defect_comments_created_at ON defect_comments(created_at);
