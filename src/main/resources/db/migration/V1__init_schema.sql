-- V1: Инициализация реляционной схемы строительного контроля
-- Совместимо с PostgreSQL 10+ и H2

-- Таблица пользователей системы
CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(64) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    full_name VARCHAR(128) NOT NULL,
    role VARCHAR(32) NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- Таблица квартир объекта
-- Уникальность квартиры определяется парой (подъезд, номер квартиры)
CREATE TABLE IF NOT EXISTS apartments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entrance_number INT NOT NULL,
    apartment_number INT NOT NULL,
    is_archived BOOLEAN DEFAULT FALSE NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT uk_entrance_apartment UNIQUE (entrance_number, apartment_number)
);

-- Индексы для быстрого поиска квартир
CREATE INDEX IF NOT EXISTS idx_apartments_archived ON apartments(is_archived);
CREATE INDEX IF NOT EXISTS idx_apartments_entrance ON apartments(entrance_number);

-- Таблица дефектов / замечаний
CREATE TABLE IF NOT EXISTS defects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    apartment_id BIGINT NOT NULL REFERENCES apartments(id) ON DELETE CASCADE,
    worker_id BIGINT NOT NULL REFERENCES users(id),
    description TEXT NOT NULL,
    urgency VARCHAR(32) NOT NULL,
    status VARCHAR(32) DEFAULT 'NEW' NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- Индексы для фильтрации дефектов на дашборде
CREATE INDEX IF NOT EXISTS idx_defects_apartment_id ON defects(apartment_id);
CREATE INDEX IF NOT EXISTS idx_defects_worker_id ON defects(worker_id);
CREATE INDEX IF NOT EXISTS idx_defects_status ON defects(status);
CREATE INDEX IF NOT EXISTS idx_defects_urgency ON defects(urgency);
CREATE INDEX IF NOT EXISTS idx_defects_created_at ON defects(created_at);

-- Таблица фотофиксации дефектов
CREATE TABLE IF NOT EXISTS defect_photos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    defect_id BIGINT NOT NULL REFERENCES defects(id) ON DELETE CASCADE,
    file_name VARCHAR(255) NOT NULL,
    original_file_name VARCHAR(255),
    storage_path VARCHAR(512) NOT NULL,
    content_type VARCHAR(64) NOT NULL,
    file_size BIGINT NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_defect_photos_defect_id ON defect_photos(defect_id);
